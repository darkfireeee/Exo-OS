// kernel/src/security/integrity_check/secure_boot.rs
//
// ═══════════════════════════════════════════════════════════════════════════════
// Secure Boot — Boot time chain of trust verification
// ═══════════════════════════════════════════════════════════════════════════════
//
// Architecture:
//   • Chain of trust: UEFI Secure Boot → Exo-Boot → Exo-Kernel
//   • Ed25519 verification at each level
//   • The bootloader passes PCR measurements in BootInfo
//   • The kernel verifies that BootInfo is signed by the Exo-Boot key
//   • TPM PCR out of scope (delegated to bootloader exo-boot/)
//
// RULE SECBOOT-01: Without verification of the chain of trust, the kernel
//                  refuses to mount the root filesystem.
// RULE SECBOOT-02: Simulated PCR measurements (without TPM) are based on BLAKE3.
// RULE SECBOOT-03: The kernel only trusts a SINGLE bootloader key.
// ═══════════════════════════════════════════════════════════════════════════════

use super::super::crypto::blake3::blake3_hash;
use super::super::crypto::ed25519::ed25519_verify;
use core::sync::atomic::{AtomicBool, Ordering};

// ─────────────────────────────────────────────────────────────────────────────
// Exo-Boot bootloader public key
// ─────────────────────────────────────────────────────────────────────────────

/// Exo-Boot bootloader Ed25519 public key.
/// Embedded in ROM — not modifiable at runtime.
static BOOTLOADER_PUBLIC_KEY: [u8; 32] = [
    0xab, 0x3d, 0x18, 0x76, 0x2e, 0x7f, 0x09, 0x4c, 0xe4, 0xa9, 0x1b, 0x35, 0x78, 0xde, 0x9c, 0x2b,
    0x4f, 0x61, 0xa7, 0x3e, 0xb0, 0x52, 0x94, 0x77, 0xc1, 0xfa, 0x38, 0x0d, 0x56, 0x9a, 0xc2, 0x6e,
];

// ─────────────────────────────────────────────────────────────────────────────
// BootAttestation — information passed by the bootloader
// ─────────────────────────────────────────────────────────────────────────────

/// Boot attestation passed by exo-boot to the kernel via BootInfo.
#[repr(C)]
pub struct BootAttestation {
    /// Magic: b"EXOATST\x00"
    pub magic: [u8; 8],
    /// Attestation version.
    pub version: u32,
    /// BLAKE3 hash of loaded kernel (code + data sections, excluding this struct).
    pub kernel_hash: [u8; 32],
    /// BLAKE3 hash of boot configuration (cmdline, etc.).
    pub config_hash: [u8; 32],
    /// TSC timestamp at boot time (additional entropy measurement).
    pub boot_tsc: u64,
    /// Unique nonce generated by the bootloader.
    pub nonce: [u8; 16],
    /// Ed25519 signature of (magic || version || kernel_hash || config_hash || boot_tsc || nonce).
    pub signature: [u8; 64],
    /// Padding for alignment.
    pub _pad: [u8; 4],
}

impl BootAttestation {
    pub const MAGIC: [u8; 8] = *b"EXOATST\x00";

    pub fn check_magic(&self) -> bool {
        self.magic == Self::MAGIC
    }

    /// Returns the data covered by the signature.
    fn signed_data(&self) -> [u8; 8 + 4 + 32 + 32 + 8 + 16] {
        let mut d = [0u8; 8 + 4 + 32 + 32 + 8 + 16];
        d[..8].copy_from_slice(&self.magic);
        d[8..12].copy_from_slice(&self.version.to_le_bytes());
        d[12..44].copy_from_slice(&self.kernel_hash);
        d[44..76].copy_from_slice(&self.config_hash);
        d[76..84].copy_from_slice(&self.boot_tsc.to_be_bytes());
        d[84..100].copy_from_slice(&self.nonce);
        d
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Secure Boot errors
// ─────────────────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Copy)]
pub enum SecureBootError {
    /// Invalid attestation (missing magic).
    InvalidAttestation,
    /// Invalid bootloader signature.
    InvalidBootloaderSignature,
    /// Kernel hash mismatch.
    KernelHashMismatch,
    /// Not initialized.
    NotInitialized,
    /// Chain of trust not verified.
    ChainNotVerified,
}

// ─────────────────────────────────────────────────────────────────────────────
// Secure Boot state
// ─────────────────────────────────────────────────────────────────────────────

struct SecureBootState {
    /// Verified boot attestation.
    attestation_verified: bool,
    /// Verified kernel hash.
    kernel_hash: [u8; 32],
    /// Boot nonce (for anti-replay).
    boot_nonce: [u8; 16],
    /// Number of verification attempts.
    verify_attempts: u32,
}

impl SecureBootState {
    const fn new() -> Self {
        Self {
            attestation_verified: false,
            kernel_hash: [0u8; 32],
            boot_nonce: [0u8; 16],
            verify_attempts: 0,
        }
    }
}

static SECBOOT_STATE: spin::Mutex<SecureBootState> = spin::Mutex::new(SecureBootState::new());
static CHAIN_VERIFIED: AtomicBool = AtomicBool::new(false);
static SECBOOT_ENFORCE: AtomicBool = AtomicBool::new(true);

// ─────────────────────────────────────────────────────────────────────────────
// Simulated PCR — integrity measurement without TPM
// ─────────────────────────────────────────────────────────────────────────────

/// Simulated PCR bank (8 registers × 32 bytes).
struct PcrBank {
    pcr: [[u8; 32]; 8],
}

impl PcrBank {
    const fn new() -> Self {
        Self {
            pcr: [[0u8; 32]; 8],
        }
    }

    /// Extends a PCR: PCR[i] = BLAKE3(PCR[i] || measurement).
    fn extend(&mut self, index: usize, measurement: &[u8]) {
        if index >= 8 {
            return;
        }
        let mut data = [0u8; 32 + 64]; // PCR(32) + measurement(≤64)
        data[..32].copy_from_slice(&self.pcr[index]);
        let mlen = measurement.len().min(64);
        data[32..32 + mlen].copy_from_slice(&measurement[..mlen]);
        self.pcr[index] = blake3_hash(&data[..32 + mlen]);
    }

    fn read(&self, index: usize) -> Option<&[u8; 32]> {
        if index >= 8 {
            None
        } else {
            Some(&self.pcr[index])
        }
    }
}

static PCR_BANK: spin::Mutex<PcrBank> = spin::Mutex::new(PcrBank::new());

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

/// Verifies the boot attestation passed by exo-boot.
///
/// Called in early boot, before any driver initialization.
pub fn verify_boot_attestation(attestation: &BootAttestation) -> Result<(), SecureBootError> {
    if !attestation.check_magic() {
        return Err(SecureBootError::InvalidAttestation);
    }

    let signed_data = attestation.signed_data();
    ed25519_verify(&BOOTLOADER_PUBLIC_KEY, &signed_data, &attestation.signature)
        .map_err(|_| SecureBootError::InvalidBootloaderSignature)?;

    // Store verified state
    let mut state = SECBOOT_STATE.lock();
    state.attestation_verified = true;
    state.kernel_hash = attestation.kernel_hash;
    state.boot_nonce = attestation.nonce;
    state.verify_attempts += 1;

    // Extend PCR[0] with the kernel hash
    drop(state);
    PCR_BANK.lock().extend(0, &attestation.kernel_hash);
    PCR_BANK.lock().extend(1, &attestation.config_hash);

    CHAIN_VERIFIED.store(true, Ordering::Release);
    Ok(())
}

/// Verifies that the chain of trust is established.
///
/// RULE SECBOOT-01: Returns Err if the chain is not verified.
pub fn check_chain_of_trust() -> Result<(), SecureBootError> {
    if !CHAIN_VERIFIED.load(Ordering::Acquire) {
        if SECBOOT_ENFORCE.load(Ordering::Relaxed) {
            return Err(SecureBootError::ChainNotVerified);
        }
    }
    Ok(())
}

/// Disables Secure Boot enforcement (debug mode only).
///
/// **DO NOT use in production.**
pub fn disable_enforcement() {
    SECBOOT_ENFORCE.store(false, Ordering::SeqCst);
}

/// FIX-F6: true if Secure Boot enforcement is active (rejection of unverified
/// binaries). Exposed for the production hardening report.
pub fn enforcement_enabled() -> bool {
    SECBOOT_ENFORCE.load(Ordering::Acquire)
}

/// Returns the boot nonce (additional entropy for the RNG).
pub fn boot_nonce() -> Option<[u8; 16]> {
    let state = SECBOOT_STATE.lock();
    if state.attestation_verified {
        Some(state.boot_nonce)
    } else {
        None
    }
}

/// Reads a simulated PCR register.
pub fn read_pcr(index: usize) -> Option<[u8; 32]> {
    PCR_BANK.lock().read(index).copied()
}

/// Extends a PCR with a measurement.
pub fn extend_pcr(index: usize, measurement: &[u8]) {
    PCR_BANK.lock().extend(index, measurement);
}

/// Returns true if the chain of trust is verified.
pub fn is_chain_verified() -> bool {
    CHAIN_VERIFIED.load(Ordering::Acquire)
}

#[derive(Debug, Clone, Copy)]
pub struct SecureBootStats {
    pub chain_verified: bool,
    pub verify_attempts: u32,
}

pub fn secureboot_stats() -> SecureBootStats {
    let state = SECBOOT_STATE.lock();
    SecureBootStats {
        chain_verified: CHAIN_VERIFIED.load(Ordering::Relaxed),
        verify_attempts: state.verify_attempts,
    }
}
