// CAP TOKEN — Unforgeable capability token (Exo-OS Security · Layer 2b)
// ═══════════════════════════════════════════════════════════════════════════════
//
// ⚠️  FORMAL PROOF SCOPE — Any modification here REQUIRES updating
//     Coq/TLA+ proofs in /proofs/kernel_security/.
//
// FUNDAMENTAL PROPERTY:
//   A CapToken is unforgeable: it can only be created via CapTable::grant()
//   which initializes { object_id, rights, generation } atomically.
//   Verification systematically compares object_id + rights + generation
//   against the table -> a revoked token returns Err(Revoked) instantaneously.
//
// MEMORY LAYOUT (24 bytes, repr(C), Rights=u32):
//   Offset  0 :  object_id   u64   — unique identifier of protected object
//   Offset  8 :  rights      u32   — bitmask of granted rights (Rights)
//   Offset 12 :  generation  u32   — revocation counter (copied from table)
//   Offset 16 :  type_tag    u16   — object type (CapObjectType)
//   Offset 18 :  _pad        u16   — explicit ABI alignment
//   Total      : 24 bytes (repr(C): 20 data + 4 padding, u64 align) — statically checked
//
// RULE CAP-01: security/capability/ is the SINGLE source of truth in the entire OS.
// RULE CAP-02: A CapToken is Copy — never shared mutable reference.
// RULE CAP-03: Generation is always copied at grant() time,
//              never recomputed afterwards. Verification compares.
// ═══════════════════════════════════════════════════════════════════════════════

use core::fmt;
use core::sync::atomic::{AtomicU64, Ordering};

use super::rights::Rights;

/// Canonical serialized size of a `CapToken` on the wire.
///
/// Complete `repr(C)` memory layout is 24 bytes due to alignment,
/// but the stable wire format only carries useful fields
/// `(object_id, rights, generation, type_tag)`.
pub const CAP_TOKEN_WIRE_SIZE: usize = 20;

// ─────────────────────────────────────────────────────────────────────────────
// Global tokens counter — Instrumentation
// ─────────────────────────────────────────────────────────────────────────────

/// Total tokens issued since startup.
static TOKENS_ISSUED: AtomicU64 = AtomicU64::new(0);

/// Total verification attempts.
static TOKENS_VERIFIED: AtomicU64 = AtomicU64::new(0);

/// Number of failed verifications (all causes combined).
static TOKENS_DENIED: AtomicU64 = AtomicU64::new(0);

// ─────────────────────────────────────────────────────────────────────────────
// ObjectId — System object identifier
// ─────────────────────────────────────────────────────────────────────────────

/// Unique identifier of a system object (IPC endpoint, VMA, file, device…).
/// Generated by CapTable — never constructed directly outside this module.
#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
#[repr(transparent)]
pub struct ObjectId(pub(super) u64);

impl ObjectId {
    /// Invalid value — never issued by CapTable.
    pub const INVALID: Self = Self(u64::MAX);

    /// Creates an ObjectId from a raw value — reserved for tests and boot.
    #[inline(always)]
    pub const fn from_raw(v: u64) -> Self {
        Self(v)
    }

    #[inline(always)]
    pub fn as_u64(self) -> u64 {
        self.0
    }

    #[inline(always)]
    pub fn is_valid(self) -> bool {
        self.0 != u64::MAX
    }
}

impl fmt::Debug for ObjectId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "ObjectId(0x{:016x})", self.0)
    }
}

impl fmt::Display for ObjectId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "oid:{:x}", self.0)
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// CapObjectType — Semantic type of referenced object
// ─────────────────────────────────────────────────────────────────────────────

/// Categorization of object referenced by a CapToken.
/// Enables type-specific verification policies.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
#[repr(u16)]
pub enum CapObjectType {
    /// Uninitialized — invalid.
    Invalid = 0,
    /// IPC endpoint (communication channel).
    IpcEndpoint = 1,
    /// Virtual memory region (VMA).
    MemoryRegion = 2,
    /// File inode.
    FileInode = 3,
    /// Device (Ring 1 driver).
    Device = 4,
    /// Thread (for signal delegation, kill, etc.).
    Thread = 5,
    /// Full process.
    Process = 6,
    /// Namespace (PID, net, mount…).
    Namespace = 7,
    /// DMA backend.
    DmaChannel = 8,
    /// IOMMU domain.
    IommuDomain = 9,
    /// Crypto key slot.
    CryptoKey = 10,
    /// Capability itself (cap delegation).
    Capability = 11,
    /// Network Pact (ExoNet V5 K1).
    NetworkPact = 12,
    /// Network Lease (ExoNet V5 K1).
    NetworkLease = 13,
    /// Network Session (ExoNet V5 K1).
    NetworkSession = 14,
    /// Portal Device (ExoNet V5 K1).
    PortalDevice = 15,
    /// Observation Scope (ExoNet V5 K1).
    ObservationScope = 16,
}

impl CapObjectType {
    /// Reconvertit depuis u16 — retourne Invalid si inconnu.
    #[inline(always)]
    pub fn from_u16(v: u16) -> Self {
        match v {
            1 => Self::IpcEndpoint,
            2 => Self::MemoryRegion,
            3 => Self::FileInode,
            4 => Self::Device,
            5 => Self::Thread,
            6 => Self::Process,
            7 => Self::Namespace,
            8 => Self::DmaChannel,
            9 => Self::IommuDomain,
            10 => Self::CryptoKey,
            11 => Self::Capability,
            12 => Self::NetworkPact,
            13 => Self::NetworkLease,
            14 => Self::NetworkSession,
            15 => Self::PortalDevice,
            16 => Self::ObservationScope,
            _ => Self::Invalid,
        }
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// CapToken — Main token (FORMAL PROOF SCOPE)
// ─────────────────────────────────────────────────────────────────────────────

/// Unforgeable capability token — 128 logical bits, 20-byte ABI layout.
///
/// # Invariants (Coq proved)
/// * `I1`: ∀ t created by `CapTable::grant`, `t.generation == table.entry[t.object_id].generation`
/// * `I2`: ∀ t revoked, `table.entry[t.object_id].generation != t.generation`
/// * `I3`: Rights of a token can never exceed delegation source rights.
///
/// # Security
/// Token is `Copy` because it is passed by value in syscalls (registers).
/// It must NEVER be mutable from userspace.
#[repr(C)]
#[derive(Copy, Clone, PartialEq, Eq)]
pub struct CapToken {
    /// Protected object identifier.
    pub(super) object_id: ObjectId,
    /// Granted rights — subset of delegation source rights.
    pub(super) rights: Rights,
    /// Copy of generation at issuance time — used to detect revocation.
    pub(super) generation: u32,
    /// Semantic type — accelerates verification without consulting table.
    pub(super) type_tag: CapObjectType,
    /// Explicit padding — guarantees zero undefined bytes (size_of == 24 due to u64 alignment).
    pub(super) _pad: u16,
}

// Static size check — Rust ABI alignment for #[repr(C)]:
// u64(8) + u32(4) + u32(4) + u16(2) + u16(2) = 20 bytes data
// but with repr(C) and align=8, total size is rounded to 24 bytes.
const _SIZE_CHECK: () = assert!(
    core::mem::size_of::<CapToken>() == 24,
    "CapToken: taille inattendue — aligner avec PROOF_SCOPE.md"
);

const _ALIGN_CHECK: () = assert!(
    core::mem::align_of::<CapToken>() == 8,
    "CapToken: alignement inattendu"
);

impl CapToken {
    /// Invalid token — never passes verification.
    pub const INVALID: Self = Self {
        object_id: ObjectId::INVALID,
        rights: Rights::NONE,
        generation: u32::MAX,
        type_tag: CapObjectType::Invalid,
        _pad: 0,
    };

    /// Constructs a token — RESERVED for `CapTable::grant()`.
    /// Called only from this module (visibility `pub(super)`).
    #[inline(always)]
    pub(crate) fn new(
        object_id: ObjectId,
        rights: Rights,
        generation: u32,
        type_tag: CapObjectType,
    ) -> Self {
        TOKENS_ISSUED.fetch_add(1, Ordering::Relaxed);
        Self {
            object_id,
            rights,
            generation,
            type_tag,
            _pad: 0,
        }
    }

    /// Returns ObjectId — read-only.
    #[inline(always)]
    pub fn object_id(self) -> ObjectId {
        self.object_id
    }

    /// Returns granted rights.
    #[inline(always)]
    pub fn rights(self) -> Rights {
        self.rights
    }

    /// Returns generation captured at issuance time.
    #[inline(always)]
    pub fn generation(self) -> u32 {
        self.generation
    }

    /// Returns object type.
    #[inline(always)]
    pub fn object_type(self) -> CapObjectType {
        self.type_tag
    }

    /// True if token holds at least requested rights.
    #[inline(always)]
    pub fn has_rights(self, required: Rights) -> bool {
        self.rights.contains(required)
    }

    /// True if token is manifestly invalid (ObjectId::INVALID).
    #[inline(always)]
    pub fn is_invalid(self) -> bool {
        self.object_id == ObjectId::INVALID
    }

    /// Converts into a 20-byte array (for userspace storage via copy_to_user).
    #[inline(always)]
    pub fn to_bytes(self) -> [u8; CAP_TOKEN_WIRE_SIZE] {
        let mut buf = [0u8; CAP_TOKEN_WIRE_SIZE];
        buf[0..8].copy_from_slice(&self.object_id.0.to_ne_bytes());
        buf[8..12].copy_from_slice(&self.rights.bits().to_ne_bytes());
        buf[12..16].copy_from_slice(&self.generation.to_ne_bytes());
        buf[16..18].copy_from_slice(&(self.type_tag as u16).to_ne_bytes());
        // _pad remains zero
        buf
    }

    /// Reconstructs from bytes (used by syscall handler on kernel side).
    /// Returns None if type_tag is unknown.
    #[inline(always)]
    pub fn from_bytes(b: &[u8; CAP_TOKEN_WIRE_SIZE]) -> Option<Self> {
        let oid = u64::from_ne_bytes(b[0..8].try_into().ok()?);
        let r = u32::from_ne_bytes(b[8..12].try_into().ok()?);
        let gen = u32::from_ne_bytes(b[12..16].try_into().ok()?);
        let tt = u16::from_ne_bytes(b[16..18].try_into().ok()?);
        let obj_type = CapObjectType::from_u16(tt);
        if obj_type == CapObjectType::Invalid {
            return None;
        }
        Some(Self {
            object_id: ObjectId(oid),
            rights: Rights::from_bits_truncate(r),
            generation: gen,
            type_tag: obj_type,
            _pad: 0,
        })
    }
}

impl fmt::Debug for CapToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CapToken")
            .field("object_id", &self.object_id)
            .field("rights", &self.rights)
            .field("generation", &self.generation)
            .field("type_tag", &self.type_tag)
            .finish()
    }
}

impl Default for CapToken {
    fn default() -> Self {
        Self::INVALID
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Statistiques globales — instrumentation
// ─────────────────────────────────────────────────────────────────────────────

/// Snapshot de statistiques de tokens.
#[derive(Debug, Clone, Copy)]
pub struct TokenStats {
    pub issued: u64,
    pub verified: u64,
    pub denied: u64,
}

/// Increments verification counter — called from revocation::verify().
#[inline(always)]
pub(super) fn stat_verified() {
    TOKENS_VERIFIED.fetch_add(1, Ordering::Relaxed);
}

/// Increments denial counter — called from revocation::verify().
#[inline(always)]
pub(super) fn stat_denied() {
    TOKENS_DENIED.fetch_add(1, Ordering::Relaxed);
}

/// Reads a coherent snapshot (each counter read independently — acceptable for perf monitoring).
pub fn read_stats() -> TokenStats {
    TokenStats {
        issued: TOKENS_ISSUED.load(Ordering::Relaxed),
        verified: TOKENS_VERIFIED.load(Ordering::Relaxed),
        denied: TOKENS_DENIED.load(Ordering::Relaxed),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn token_wire_roundtrip_preserves_valid_type() {
        let token = CapToken::new(
            ObjectId::from_raw(0x1234),
            Rights::IPC_SEND,
            7,
            CapObjectType::IpcEndpoint,
        );

        let decoded = CapToken::from_bytes(&token.to_bytes()).expect("valid token wire form");
        assert_eq!(decoded.object_id(), token.object_id());
        assert_eq!(decoded.rights(), token.rights());
        assert_eq!(decoded.generation(), token.generation());
        assert_eq!(decoded.object_type(), token.object_type());
    }

    #[test]
    fn token_wire_rejects_unknown_type_tag() {
        let mut bytes = CapToken::new(
            ObjectId::from_raw(0x1234),
            Rights::IPC_SEND,
            7,
            CapObjectType::IpcEndpoint,
        )
        .to_bytes();
        bytes[16..18].copy_from_slice(&0xffffu16.to_ne_bytes());

        assert!(CapToken::from_bytes(&bytes).is_none());
    }
}
